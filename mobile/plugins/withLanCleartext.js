/**
 * Config plugin: let the app talk plain HTTP to the AionDX bridge on the LAN.
 *
 * Android 9+ blocks cleartext by default. The bridge's addresses are arbitrary private IPs
 * (and Tailscale 100.x), so they can't be domain-scoped; cleartext is allowed app-wide via an
 * explicit network security config. That's acceptable because every payload is sealed
 * end to end (contract §7). An explicit config (rather than only the manifest's
 * usesCleartextTraffic flag) is used because a network security config, if any library adds
 * one, silently overrides that flag.
 *
 * Generated into the native project by `expo prebuild` (CNG). Never edit android/ by hand.
 */
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const XML_NAME = 'aiondx_network_security_config';
const XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withLanCleartext.js. AionDX bridge traffic is end-to-end sealed. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

function withNetworkSecurityXml(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${XML_NAME}.xml`), XML);
      return cfg;
    },
  ]);
}

function withNetworkSecurityManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:networkSecurityConfig'] = `@xml/${XML_NAME}`;
    return cfg;
  });
}

module.exports = function withLanCleartext(config) {
  return withNetworkSecurityManifest(withNetworkSecurityXml(config));
};
